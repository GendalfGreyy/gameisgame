export function buildStudioSceneFromTemplate(template: StudioTemplateId): StudioScene {
  switch (template) {
    case 'empty':
      return emptyStudioScene();
    case 'collector':
      return collectorStudioScene();
    case 'platformer':
      return platformerStudioScene();
  }
}
